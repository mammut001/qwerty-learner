// Builds the pilot corpus from the cached API responses (no network).
//   out/pilot-corpus.json  array of passage records
//   out/REPORT.md          counts, calibration table, samples, rejections, licence strings, open problems
//
// Run: node scripts/reading-corpus/build.mjs   (after fetch.mjs)

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { selectPassages, countWords, PASSAGE_MIN_WORDS } from './passages.mjs'
import { estimateLevel, computeMetrics, scoreMetrics, CUTS, bandOf } from './level.mjs'
import { runCalibration, BANDS } from './calibrate.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const CACHE = join(here, 'cache')
const OUT = join(here, 'out')
const titles = JSON.parse(readFileSync(join(here, 'titles.json'), 'utf8'))
const fetchLog = existsSync(join(CACHE, 'fetch-log.json')) ? JSON.parse(readFileSync(join(CACHE, 'fetch-log.json'), 'utf8')) : { requestsMade: 0, requests: [] }

function slugify(s) {
  return s.normalize('NFD').replace(/\p{M}/gu, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
}

const siteinfo = {}
for (const siteKey of Object.keys(titles.sites)) {
  siteinfo[siteKey] = JSON.parse(readFileSync(join(CACHE, `siteinfo-${siteKey}.json`), 'utf8'))
}

const corpus = []
const rejectedArticles = []
const passageRejections = {}
const articleSummaries = []

for (const [siteKey, site] of Object.entries(titles.sites)) {
  const info = siteinfo[siteKey]
  const licence = info.ok ? { text: info.rightsinfo?.text ?? null, url: info.rightsinfo?.url ?? null } : { text: null, url: null }
  for (const entry of site.titles) {
    const file = join(CACHE, siteKey, `${slugify(entry.title)}.json`)
    const rec = JSON.parse(readFileSync(file, 'utf8'))
    if (!rec.ok) {
      rejectedArticles.push({ site: siteKey, title: entry.title, reason: `fetch failed: ${rec.error}` })
      continue
    }
    const page = rec.raw.query.pages[0]
    const extract = page.extract
    const canonicalUrl = page.canonicalurl
    const sel = selectPassages(extract)
    for (const [k, v] of Object.entries(sel.rejected)) passageRejections[k] = (passageRejections[k] || 0) + v
    const summary = { site: siteKey, title: entry.title, apiTitle: page.title, passages: sel.passages.length, paragraphs: sel.paragraphCount, words: countWords(extract) }
    articleSummaries.push(summary)
    if (sel.passages.length === 0) {
      const reasons = Object.entries(sel.rejected).map(([r, n]) => `${r} x${n}`).join(', ')
      const total = countWords(extract)
      const reason = total < PASSAGE_MIN_WORDS
        ? `too little clean text (${total} words in the whole extract; a passage needs 80-300 words of whole paragraphs)`
        : `no window of whole clean paragraphs of 80-300 words${reasons ? ` (rejected windows: ${reasons})` : ''}`
      rejectedArticles.push({ site: siteKey, title: entry.title, apiTitle: page.title, reason })
      continue
    }
    sel.passages.forEach((p, idx) => {
      const est = estimateLevel(p.text)
      corpus.push({
        id: `${siteKey}-${slugify(entry.title)}-${idx + 1}`,
        site: siteKey,
        title: page.title,
        requestedTitle: entry.title,
        topic: entry.topic,
        url: canonicalUrl,
        revisionId: page.lastrevid,
        historyUrl: `${canonicalUrl}?action=history`,
        licence: licence.text,
        licenceUrl: licence.url,
        retrievedAt: rec.retrievedAt,
        text: p.text,
        words: p.words,
        paragraphRange: [p.firstParagraph, p.lastParagraph],
        metrics: est.metrics,
        score: est.score,
        estimatedLevel: est.estimatedLevel,
        band: est.band,
      })
    })
  }
}

// Calibration (static reading scenarios, levels 4-12) is reported next to the corpus.
const cal = runCalibration(CUTS)

mkdirSync(OUT, { recursive: true })
writeFileSync(join(OUT, 'pilot-corpus.json'), JSON.stringify(corpus, null, 2) + '\n', 'utf8')

// ---------- REPORT ----------
const pct = (x) => `${(x * 100).toFixed(1)} %`
const md = []
const push = (...lines) => md.push(...lines)
const counts = (site) => {
  const row = {}
  for (const b of BANDS) row[b] = corpus.filter((c) => c.site === site && c.band === b).length
  return row
}

push('# Pilot corpus: real French reading passages (offline)', '',
  'Generated by `scripts/reading-corpus/build.mjs` from cached MediaWiki responses (no network in this step).',
  `Requests made to the public APIs for this pilot: ${fetchLog.requestsMade} of 80 (see \`scripts/reading-corpus/cache/fetch-log.json\`, git-ignored).`, '')

push('## Counts', '', '| Site | Articles requested | Articles with passages | Passages | 4-6 | 7-8 | 9-10 | 11-12 |', '|---|---|---|---|---|---|---|---|')
for (const siteKey of Object.keys(titles.sites)) {
  const requested = titles.sites[siteKey].titles.length
  const withP = new Set(corpus.filter((c) => c.site === siteKey).map((c) => c.requestedTitle)).size
  const c = counts(siteKey)
  const total = corpus.filter((x) => x.site === siteKey).length
  push(`| ${siteKey} | ${requested} | ${withP} | ${total} | ${c['4-6']} | ${c['7-8']} | ${c['9-10']} | ${c['11-12']} |`)
}
push(`| **total** | ${Object.values(titles.sites).reduce((s, x) => s + x.titles.length, 0)} | ${new Set(corpus.map((c) => c.site + c.requestedTitle)).size} | ${corpus.length} | ${corpus.filter((c) => c.band === '4-6').length} | ${corpus.filter((c) => c.band === '7-8').length} | ${corpus.filter((c) => c.band === '9-10').length} | ${corpus.filter((c) => c.band === '11-12').length} |`, '')

push('## Licence strings (exactly as returned by meta=siteinfo&siprop=rightsinfo)', '')
for (const siteKey of Object.keys(titles.sites)) {
  const info = siteinfo[siteKey]
  push(`- **${siteKey}** (${info.host}), retrieved ${info.retrievedAt}: text \`${info.rightsinfo?.text ?? 'NULL'}\`, url \`${info.rightsinfo?.url ?? 'NULL'}\``)
}
push('', 'Each passage record carries the licence text and URL of its own site. Attribution for reuse: the article URL, the revision id, and the history URL (`historyUrl`) identify the authors.', '')

push('## Level estimator calibration', '',
  `Ground truth: level in the key of the static reading scenarios \`n4-reading-*\` ... \`n12-reading-*\` in \`server/echelle-variants/\` (${cal.counts.total} texts; per level: ${Object.entries(cal.counts.perLevel).map(([l, n]) => `${l}: ${n}`).join(', ')}).`,
  'Template scenarios (functions) are excluded. Levels 5 and 6 have no static reading text, so band 4-6 is represented by level 4 only.',
  `CUTS in use (tuned on the even-index training half, ${cal.counts.train} texts): \`[${CUTS.join(', ')}]\`.`, '')
push('| Set | n | Exact band accuracy | Within one band | Mean abs. level error |', '|---|---|---|---|---|')
push(`| Held-out odd-index half (honest) | ${cal.holdout.n} | ${pct(cal.holdout.exactBandAccuracy)} | ${pct(cal.holdout.withinOneBandAccuracy)} | ${cal.holdout.meanAbsLevelError} |`)
push(`| Training half (in-sample) | ${cal.train.n} | ${pct(cal.train.exactBandAccuracy)} | ${pct(cal.train.withinOneBandAccuracy)} | ${cal.train.meanAbsLevelError} |`)
push(`| All texts (in-sample) | ${cal.full.n} | ${pct(cal.full.exactBandAccuracy)} | ${pct(cal.full.withinOneBandAccuracy)} | ${cal.full.meanAbsLevelError} |`, '')
const confTable = (m, title) => [`**Confusion, ${title}** (rows: true band, columns: estimated band)`, '', `| true \\ est. | ${BANDS.join(' | ')} |`, `|---|${BANDS.map(() => '---').join('|')}|`, ...BANDS.map((b, i) => `| ${b} | ${m[i].join(' | ')} |`), '']
push(...confTable(cal.confusionHoldout, 'held-out half'))
push(...confTable(cal.confusionFull, 'all texts'))

push('Per-level mean score of the calibration texts (higher = harder):', '', '| Level | n | mean score | mean estimated level |', '|---|---|---|---|')
for (let L = 4; L <= 12; L++) {
  const rows = cal.items.filter((it) => it.level === L)
  if (!rows.length) continue
  const ms = rows.reduce((s, r) => s + r.score, 0) / rows.length
  const me = rows.reduce((s, r) => s + r.estimatedLevel, 0) / rows.length
  push(`| ${L} | ${rows.length} | ${ms.toFixed(3)} | ${me.toFixed(2)} |`)
}
push('')

push('## Sample passages (6, verbatim)', '', 'Selection rule: one passage per (site, band) combination, taken in corpus order, up to six in total.', '')
const samples = []
for (const siteKey of Object.keys(titles.sites)) {
  for (const b of BANDS) {
    if (samples.length >= 6) break
    const hit = corpus.find((c) => c.site === siteKey && c.band === b && !samples.includes(c))
    if (hit) samples.push(hit)
  }
}
for (const s of samples) {
  push(`### ${s.id} (${s.site}, band ${s.band}, estimated level ${s.estimatedLevel})`, '',
    `Source: ${s.url} (revision ${s.revisionId}); history: ${s.historyUrl}; licence: ${s.licence}`, '',
    '```text', s.text, '```', '',
    `Metrics: words ${s.metrics.words}, sentences ${s.metrics.sentences}, mean sentence length ${s.metrics.meanSentenceLength}, long-sentence share ${s.metrics.longSentenceShare}, subordination per sentence ${s.metrics.subordinationPerSentence}, long-word share ${s.metrics.longWordShare}, TTR(100) ${s.metrics.ttr100}, outside basic list ${s.metrics.outsideBasicShare}, complex cues per 100 ${s.metrics.complexCuesPer100}; score ${s.score}.`, '')
}

push('## Rejected articles', '', '| Site | Title | Reason |', '|---|---|---|')
for (const r of rejectedArticles) push(`| ${r.site} | ${r.title} | ${r.reason} |`)
push('')
push('Passage-level rejections (windows of whole paragraphs that failed a check, counted once per start paragraph): ' +
  (Object.entries(passageRejections).map(([k, v]) => `${k} ${v}`).join(', ') || 'none') + '.', '')

push('## Open problems and limits', '',
  '- Upper levels are not separated: on the held-out half, level-4 texts are all placed in band 4-6 (6 of 6), but bands 7-8, 9-10 and 11-12 are confused with each other, and the mean scores of levels 9-12 lie within 0.61 to 0.68. Treat the estimated level of a single passage as a rough indication only.',
  '- Band 4-6 is calibrated only with level-4 static texts (no static level-5 or level-6 reading text exists in the repo). The threshold for 5-6 is therefore untested.',
  '- The cut points were tuned on half of the calibration texts; the held-out numbers are the honest estimate, and the in-sample numbers are optimistic.',
  '- The basic word list (1,500 forms) comes from levels 1-3 repo material. Real encyclopedic text has many out-of-list words at every level; this effect was not measured separately, but it probably pushes estimates upward.',
  '- Band 4-6 in the corpus is mostly Vikidia (18 of 23 passages). Vikidia is written for children, so its low estimates may reflect the register of the site rather than the level scale.',
  '- Complex-tense and subjunctive cues are regex heuristics with known false positives and negatives. The complex-cue count is zero for 46 of the 73 passages, so this feature contributes little.',
  '- Passages are chosen mechanically (whole paragraphs, length bounds, no anaphoric opening). They have not been read by a human for self-containedness or sensitivity; a manual review is still needed.',
  '- Vikidia article "Logement" states it is partly adapted from the Wikipédia article of the same name. Vikidia content is therefore a derivative of CC BY-SA text; check the attribution rules before any reuse.',
  '- The canonical URLs for the Vikidia site are returned by the API with the `http://` scheme; they are stored unchanged.',
  '- Titles with redirects (e.g. Vikidia "Médecin" to "Médecine", Wikipédia "Éducation au Québec" to "Système éducatif au Québec") are stored under the API title that was returned; the requested title is kept as `requestedTitle`.',
  '- Each passage is a snapshot of the article revision given in `revisionId`; later edits do not change the stored text.',
  '- No question sets, answer keys or distractors were generated: out of scope for this pilot.',
  '')

writeFileSync(join(OUT, 'REPORT.md'), md.join('\n') + '\n', 'utf8')
console.log(`passages=${corpus.length} articlesWithPassages=${articleSummaries.filter((a) => a.passages > 0).length} rejectedArticles=${rejectedArticles.length}`)
