test('practice results fit a short viewport and scroll to bottom actions', async ({ page }) => {
  await page.setViewportSize({ width: 700, height: 500 })
  await page.goto('/word-lists')
  await page.getByLabel('词表名称').fill('结果小窗口验证')
  await page.getByLabel('词条', { exact: true }).fill('a = 一个')
  await page.getByTestId('word-list-practise').click()
  await expect(page.getByRole('link', { name: '结果小窗口验证' })).toBeVisible()
  await page.keyboard.press('Enter')
  await expect(page.locator('textarea')).toBeFocused()
  await page.keyboard.insertText('a')
  const dialog = page.getByRole('dialog', { name: '结果小窗口验证 第1章', exact: true })
  await expect(dialog).toBeVisible()
  const panel = dialog.getByText('结果小窗口验证 第1章', { exact: true }).locator('..')
  await expect.poll(async () => (await panel.boundingBox())?.y ?? -1000).toBeGreaterThanOrEqual(8)
  const box = await panel.boundingBox()
  expect(box!.y + box!.height).toBeLessThanOrEqual(492)
  expect(await panel.evaluate((element) => element.scrollHeight > element.clientHeight)).toBe(true)
  await panel.evaluate((element) => {
    element.scrollTop = element.scrollHeight
  })
  expect(await panel.evaluate((element) => element.scrollTop)).toBeGreaterThan(0)
  await dialog.getByRole('button', { name: '重复本章节', exact: true }).click()
  await expect(dialog).not.toBeAttached()
  await expect(page.locator('textarea')).toBeFocused()
})
