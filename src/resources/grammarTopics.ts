import { type GrammarScenario, grammarBatches, passeComposeVsImparfaitScenarios } from './grammarSessions'

export type GrammarTopic = {
  id: string
  /** Stored as the session topic; keep stable once sessions have been recorded. */
  topic: string
  title: string
  tagline: string
  level: string
  reminder: string
  rule: string
  reasonPlaceholder: string
  scenarios: GrammarScenario[]
  batches: { title: string; questionIds: number[] }[]
  outputPrompts: { zh: string; hint: string }[]
}

type Row = [
  prompt: string,
  a: string,
  b: string,
  correct: 'A' | 'B',
  explanation: string,
  translation: string,
  signal: string,
  vocabulary?: string[],
]

// Question ids are unique across topics (topic N starts at N * 100 + 1) because the server keys grammar errors by id.
const scenarios = (firstId: number, rows: Row[]): GrammarScenario[] =>
  rows.map(([prompt, a, b, correct, explanation, translation, signal, vocabulary], index) => ({
    id: firstId + index,
    prompt,
    options: [
      { label: 'A', text: a },
      { label: 'B', text: b },
    ],
    correct,
    explanation,
    translation,
    signal,
    ...(vocabulary ? { vocabulary } : {}),
  }))

const batchesFrom = (firstId: number, titles: [string, string, string]) => [
  { title: `第 1 组 · ${titles[0]}`, questionIds: [0, 1, 2, 3].map((offset) => firstId + offset) },
  { title: `第 2 组 · ${titles[1]}`, questionIds: [4, 5, 6, 7].map((offset) => firstId + offset) },
  { title: `第 3 组 · ${titles[2]}`, questionIds: [8, 9].map((offset) => firstId + offset) },
]

